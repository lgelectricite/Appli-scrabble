  function cle(state) {
    var base = state.manche + ':' + state.round;
    if (state.phase === 'clue') return 'clue:' + base + ':' + state.orderPos;
    if (state.phase === 'debat' || state.phase === 'vote' || state.phase === 'white') return state.phase + ':' + base;
    return '';
  }
  function armer(state, ms, toujours) {
    var k = cle(state);
    if (!k || (!state.opts.chrono && !toujours)) { state.ech = null; return null; }
    state.ech = { k: k, fin: Date.now() + ms, duree: ms };
    return { ms: ms + 400, action: { t: 'expire', k: k } };
  }

