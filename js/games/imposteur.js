  function startManche(state) {
    var paire = tirerPaire(state.opts);
    var mots = Math.random() < 0.5 ? [paire.a, paire.b] : [paire.b, paire.a];
    state.pair = mots; // [mot des civils, mot des imposteurs]
    state.paireCat = paire.cat;
    var n = state.players.length;
    var idx = GG.shuffle(state.players.map(function (_, i) { return i; }));
    var nImp = nbImposteurs(n);
    var white = state.opts.white && n >= 5 ? idx[nImp] : -1;
    state.players.forEach(function (p, i) {
      var k = idx.indexOf(i);
      p.alive = true;
      p.role = k < nImp ? 'imposteur' : (i === white ? 'white' : 'civil');
      p.word = p.role === 'imposteur' ? mots[1] : (p.role === 'white' ? '' : mots[0]);
      p.seen = false;
      p.vote = -1;
    });
    state.phase = 'reveal';
    state.order = [];
    state.orderPos = 0;
    state.tours = [];
    state.round = 0;
    state.lastResult = null;
    state.whiteTry = null;
    state.winner = '';
    state.ech = null;
    state.peek = -1;
    state.mancheId = Math.floor(Math.random() * 1e9);
  }

  function newSpeakRound(state) {
    var ordre = GG.shuffle(alive(state));
    // Mister White ne parle jamais en premier (il n'a aucun mot à reprendre)
    if (ordre.length > 1 && state.players[ordre[0]].role === 'white') {
      var w = ordre.shift();
      ordre.splice(1 + Math.floor(Math.random() * (ordre.length - 1)), 0, w);
    }
    state.order = ordre;
    state.orderPos = 0;
    state.tours.push([]);
    state.round++;
    state.phase = 'clue';
    state.players.forEach(function (p) { p.vote = -1; });
    return armer(state, state.opts.oral ? DUREE.oral : DUREE.clue);
  }

  function avancerIndice(state) {
    state.orderPos++;
    if (state.orderPos < state.order.length) {
      return armer(state, state.opts.oral ? DUREE.oral : DUREE.clue);
    }
    if (state.opts.debat > 0) {
      state.phase = 'debat';
      return armer(state, state.opts.debat * 1000, true);
    }
    return ouvrirVote(state);
  }

  function ouvrirVote(state) {
    state.phase = 'vote';
    alive(state).forEach(function (i) { state.players[i].vote = -1; });
    return armer(state, DUREE.vote);
  }

  /* dépouillement (les absents s'abstiennent) */
  function resolveVotes(state) {
    var counts = {}, ballots = [];
    alive(state).forEach(function (i) {
      var v = state.players[i].vote;
      if (v >= 0) { counts[v] = (counts[v] || 0) + 1; ballots.push({ de: i, pour: v }); }
    });
    var best = -1, bestN = 0, tie = false;
    Object.keys(counts).forEach(function (k) {
      if (counts[k] > bestN) { bestN = counts[k]; best = parseInt(k, 10); tie = false; }
      else if (counts[k] === bestN) tie = true;
    });
    var detail = Object.keys(counts).map(function (k) {
      return { p: parseInt(k, 10), n: counts[k] };
    }).sort(function (a, b) { return b.n - a.n; });
    state.ech = null;
    if (tie || best < 0) {
      state.lastResult = { tie: true, out: -1, role: '', votes: detail, ballots: ballots, id: state.manche + ':' + state.round };
      state.phase = 'result';
      return null;
    }
    state.players[best].alive = false;
    state.lastResult = { tie: false, out: best, role: state.players[best].role, votes: detail, ballots: ballots,
      id: state.manche + ':' + state.round };
    if (state.players[best].role === 'white') {
      state.phase = 'white';
      return armer(state, DUREE.white);
    }
    return conclure(state);
  }

  /* la manche est-elle jouée ? */
  function conclure(state) {
    var c = countRoles(state);
    var vivants = c.imp + c.civ + c.white;
    if (c.imp === 0 && c.white === 0) return finManche(state, 'civils');
    if ((c.imp >= 1 && c.civ <= c.imp) || (vivants <= 2 && c.imp + c.white >= 1)) {
      return finManche(state, c.imp >= 1 ? 'imposteurs' : 'white');
    }
    state.phase = 'result';
    state.ech = null;
    return null;
  }

  function finManche(state, qui) {
    state.winner = qui;
    state.phase = 'end';
    state.ech = null;
    state.players.forEach(function (p) {
      p.gain = 0;
      if (qui === 'civils' && p.role === 'civil') p.gain = 3;
      if (qui === 'imposteurs' && p.role === 'imposteur') p.gain = 5;
      if ((qui === 'imposteurs' || qui === 'white') && p.role === 'white' && p.alive) p.gain = 6;
      if (qui === 'whiteDevine' && p.role === 'white') p.gain = 6;
      p.score += p.gain;
    });
    return null;
  }

  /* une phase arrive à son terme (minuteur écoulé, ou l'hôte passe) */
  function echeance(state) {
    if (state.phase === 'clue') {
      var sp = state.order[state.orderPos];
      state.tours[state.tours.length - 1].push({ p: sp, text: '', passe: true });
      return avancerIndice(state);
    }
    if (state.phase === 'debat') return ouvrirVote(state);
    if (state.phase === 'vote') return resolveVotes(state);
    if (state.phase === 'white') {
      state.whiteTry = { p: state.lastResult.out, text: '', ok: false };
      return conclure(state);
    }
    return null;
  }

  /* comparaison tolérante : « un chat », « Chats », « le CHAT » */
  var VIDES = ['LE', 'LA', 'LES', 'L', 'UN', 'UNE', 'DES', 'DU', 'DE', 'D', 'CEST', 'C', 'EST', 'MON', 'MA', 'MES'];
  function motNorm(s) {
    var t = String(s || '').toUpperCase().replace(/Œ/g, 'OE').replace(/Æ/g, 'AE')
      .normalize('NFD').replace(/[̀-ͯ]/g, '');
    var mots = t.replace(/[^A-Z0-9]+/g, ' ').trim().split(' ').filter(Boolean);
    while (mots.length > 1 && VIDES.indexOf(mots[0]) !== -1) mots.shift();
    return mots.join('');
  }
  function memeMot(a, b) {
    var x = motNorm(a), y = motNorm(b);
    if (!x || !y) return false;
    return x === y || x.replace(/[SX]$/, '') === y.replace(/[SX]$/, '');
  }

  /* ================================================================
   * 6. L'adversaire IA
   *    Il ne regarde que ce que le joueur assis à sa place sait : SON mot,
   *    les indices publics et qui est en vie. Ses indices portent TOUJOURS
   *    sur son propre mot (un imposteur qui s'ignore en fait autant).
   * ================================================================ */
  function clueOk(text, word) {
    var t = String(text || '').trim();
    if (!t || t.length > 20 || /\s/.test(t)) return false;
    var nc = norm(t), nw = norm(word);
    if (!nc) return false;
    return !(nw && (nc.indexOf(nw) !== -1 || nw.indexOf(nc) !== -1));
  }
  function usedClues(state) {
    var set = {};
    (state.tours || []).forEach(function (tour) {
      tour.forEach(function (c) { if (c.text) set[norm(c.text)] = true; });
    });
    return set;
  }
  function entendus(state, me) {
    var out = [];
    (state.tours || []).forEach(function (tour) {
      tour.forEach(function (c) { if (c.p !== me && c.text) out.push(norm(c.text)); });
    });
    return out;
  }
  /* le mot le plus probable des autres, d'après les indices entendus */
  function motProbable(state, me, sauf) {
    var score = {};
    entendus(state, me).forEach(function (n) {
      (ASSOC_REV[n] || []).forEach(function (w) { if (w !== sauf) score[w] = (score[w] || 0) + 1; });
    });
    var best = null, bestN = 0;
    Object.keys(score).forEach(function (w) {
      if (score[w] > bestN || (score[w] === bestN && Math.random() < 0.5)) { best = w; bestN = score[w]; }
    });
    return best;
  }
  function botClue(state, me) {
    var p = state.players[me];
    var word = p.word || '';
    var used = usedClues(state);
    function frais(liste, ref) {
      return (liste || []).filter(function (a) { return clueOk(a, ref) && !used[norm(a)]; });
    }
    if (p.role === 'white' || !word) {
      // Mister White : il reprend le thème des autres, sans mot à lui
      var cible = motProbable(state, me, null);
      var e = cible ? frais(ASSOC_N[cible], '') : [];
      if (e.length) return pick(e);
      var f = FLOUS.filter(function (a) { return !used[norm(a)]; });
      return f.length ? pick(f) : 'MYSTÈRE';
    }
    var pool = frais(ASSOC_N[norm(word)], word);
    if (!pool.length) {
      // tout a été dit : on reprend une association de SON mot déjà entendue
      // chez les autres (« moi aussi : … »), jamais une des siennes
      var dejaDit = {};
      (state.tours || []).forEach(function (tour) {
        tour.forEach(function (c) { if (c.p === me && c.text) dejaDit[norm(c.text)] = true; });
      });
      var echo = (ASSOC_N[norm(word)] || []).filter(function (a) { return clueOk(a, word) && !dejaDit[norm(a)]; });
      if (echo.length) return pick(echo);
      var fl = FLOUS.filter(function (a) { return clueOk(a, word) && !used[norm(a)]; });
      return fl.length ? pick(fl) : 'MYSTÈRE';
    }
    // doute sur soi : si les indices entendus ne collent pas à mon mot, je
    // choisis parmi MES associations la plus « passe-partout » (celle que
    // d'autres mots partagent), pour ne rien dévoiler
    var mine = {};
    (ASSOC_N[norm(word)] || []).forEach(function (a) { mine[norm(a)] = true; });
    var ent = entendus(state, me), collent = ent.filter(function (n) { return mine[n]; }).length;
    if (ent.length >= 2 && collent * 2 < ent.length) {
      pool.sort(function (a, b) { return (ASSOC_REV[norm(b)] || []).length - (ASSOC_REV[norm(a)] || []).length; });
      return pool[0];
    }
    return pick(pool);
  }
  function botVote(state, me) {
    var p = state.players[me];
    var mine = {};
    var ref = p.word ? norm(p.word) : motProbable(state, me, null);
    (ASSOC_N[ref] || []).forEach(function (a) { mine[norm(a)] = true; });
    var autres = alive(state).filter(function (i) { return i !== me; });
    if (Math.random() < 0.2) return pick(autres); // l'IA n'est pas voyante
    var cible = autres[0], pire = -Infinity;
    autres.forEach(function (i) {
      var s = 0;
      (state.tours || []).forEach(function (tour) {
        tour.forEach(function (c) {
          if (c.p !== i) return;
          if (c.passe) { s += 0.6; return; }
          if (!c.text) return;
          var n = norm(c.text);
          if (mine[n]) s -= 0.5;
          else if (ASSOC_REV[n]) s += 0.75;
          else s += 0.4;
        });
      });
      s += Math.random() * 3.5;
      if (s > pire) { pire = s; cible = i; }
    });
    return cible;
  }

